"""Глобальные константы приложения «Лесной помощник».

Все «магические числа» и строки собраны здесь, чтобы их можно было
изменить в одном месте без правки остального кода.
"""

from __future__ import annotations

import re
from typing import Final

# ---------------------------------------------------------------------------
# Метаданные приложения
# ---------------------------------------------------------------------------

APP_NAME: Final[str] = "Лесной помощник"
APP_ID: Final[str] = "forest_assistant"
APP_VERSION: Final[str] = "1.0.0"
APP_DESCRIPTION: Final[str] = "Инструменты сотрудника лесного хозяйства"

# ---------------------------------------------------------------------------
# Окно
# ---------------------------------------------------------------------------

WINDOW_DEFAULT_WIDTH: Final[int] = 1240
WINDOW_DEFAULT_HEIGHT: Final[int] = 800
WINDOW_MIN_WIDTH: Final[int] = 1060
WINDOW_MIN_HEIGHT: Final[int] = 700

# ---------------------------------------------------------------------------
# Боковая панель
# ---------------------------------------------------------------------------

SIDEBAR_WIDTH: Final[int] = 272
SIDEBAR_COLLAPSED_WIDTH: Final[int] = 84

# ---------------------------------------------------------------------------
# Анимации (миллисекунды)
# ---------------------------------------------------------------------------

ANIMATION_FAST_MS: Final[int] = 150
ANIMATION_MEDIUM_MS: Final[int] = 250
ANIMATION_SLOW_MS: Final[int] = 400

