#: Формат имени выходного файла: «КВ XX В YY» (например, «КВ 18 В 12»).
#: Допускаются строчные буквы и любое количество пробелов — значение
#: нормализуется к каноническому виду «КВ 18 В 12».
OUTPUT_NAME_PATTERN: Final[re.Pattern[str]] = re.compile(
    r"^\s*КВ\s+(\d{1,4})\s+В\s+(\d{1,4})\s*$",
    re.IGNORECASE,
)

OUTPUT_NAME_HINT: Final[str] = "КВ 18 В 12"
OUTPUT_NAME_HELPER: Final[str] = "Формат: «КВ <квартал> В <выдел>», например «КВ 18 В 12»"

# ---------------------------------------------------------------------------
# Хранение данных
# ---------------------------------------------------------------------------

SETTINGS_FILE_NAME: Final[str] = "settings.json"
LOG_FILE_NAME: Final[str] = "forest_assistant.log"
LOG_MAX_BYTES: Final[int] = 5 * 1024 * 1024  # 5 МБ на файл
